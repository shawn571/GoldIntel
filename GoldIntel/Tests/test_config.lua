--[[
Tests / test_config.lua                                       (Phase 2: Core/Config.lua)
]]

local T = require('testlib')
local Loader = require('loader')

local function boot(preload)
  local Fake = require('fake_wow')
  local W = Fake.new()
  if preload then preload(W) end
  local P, ns = Loader.load(W.env)
  W:login()
  return W, P, ns, ns.Config
end

T.describe('Config definitions', function()
  T.it('ships the Contracts F6 settings with their defaults', function()
    local _, _, _, C = boot()
    T.eq(C.Get('idleSec'), 120)
    T.eq(C.Get('minSegSec'), 600)
    T.eq(C.Get('minBinSec'), 60)
    T.eq(C.Get('heatGrid'), 32)
    T.eq(C.Get('valuation'), 'conservative')
    T.eq(C.Get('defaultSellThrough'), 0.6)
    T.eq(C.Get('prune.days'), 90)
    T.eq(C.Get('prune.maxBytes'), 2000000)
    T.eq(C.Get('normalization.minHours'), 5)
    T.eq(C.Get('normalization.bracketSize'), 5)
  end)

  T.it('Define validates keys, specs, defaults and conflicts', function()
    local _, _, _, C = boot()
    T.truthy(C.Define('my.flag', { type = 'boolean', default = false }))
    T.isnil((C.Define('my.flag', { type = 'boolean', default = false })))
    T.isnil((C.Define('bad key', { type = 'boolean', default = false })))
    T.isnil((C.Define('a..b', { type = 'boolean', default = false })))
    T.isnil((C.Define('trail.', { type = 'boolean', default = false })))
    T.isnil((C.Define('', { type = 'boolean', default = false })))
    T.isnil((C.Define('x1', 'spec')))
    T.isnil((C.Define('x2', { type = 'float', default = 1 })))
    T.isnil((C.Define('x3', { type = 'number', default = 'text' })))
    T.isnil((C.Define('x4', { type = 'number', default = 5, minValue = 10 })))
    T.isnil((C.Define('x5', { type = 'enum', default = 'a', values = {} })))
    T.isnil((C.Define('my', { type = 'boolean', default = false })), 'parent of an existing dotted key')
    T.isnil((C.Define('my.flag.deeper', { type = 'boolean', default = false })), 'child of an existing key')
  end)

  T.it('Spec returns a copy; List is sorted and describes each setting', function()
    local _, _, _, C = boot()
    local spec = C.Spec('idleSec')
    spec.default = 1
    T.eq(C.Get('idleSec'), 120)
    T.isnil(C.Spec('nope'))
    local list = C.List()
    for i = 2, #list do T.truthy(list[i - 1].key < list[i].key) end
    T.eq(list[1].key, 'collect.auto')
    T.truthy(list[1].isDefault)
    T.eq(list[1].default, true)
  end)
end)

T.describe('Config values', function()
  T.it('Set validates type, range, integer-ness, enums and read-only', function()
    local _, _, _, C = boot()
    T.truthy(C.Set('idleSec', 200))
    local ok, err = C.Set('idleSec', 5);        T.isnil(ok); T.truthy(err:find('at least 10', 1, true))
    ok, err = C.Set('idleSec', 99999);          T.isnil(ok); T.truthy(err:find('at most 3600', 1, true))
    ok, err = C.Set('idleSec', 12.5);           T.isnil(ok); T.truthy(err:find('whole number', 1, true))
    ok, err = C.Set('idleSec', '200');          T.isnil(ok); T.truthy(err:find('must be a number', 1, true))
    ok, err = C.Set('idleSec', 0 / 0);          T.isnil(ok)
    ok, err = C.Set('idleSec', math.huge);      T.isnil(ok)
    ok, err = C.Set('valuation', 'cheap');      T.isnil(ok); T.truthy(err:find('one of', 1, true))
    ok, err = C.Set('heatGrid', 32);            T.isnil(ok); T.truthy(err:find('read-only', 1, true))
    ok, err = C.Set('nope', 1);                 T.isnil(ok); T.truthy(err:find('unknown setting', 1, true))
    T.eq(C.Get('idleSec'), 200, 'invalid sets leave the value alone')
  end)

  T.it('booleans and strings are validated', function()
    local _, _, _, C = boot()
    C.Define('my.flag', { type = 'boolean', default = false })
    C.Define('my.name', { type = 'string', default = 'x', maxLength = 5 })
    T.truthy(C.Set('my.flag', true))
    T.isnil((C.Set('my.flag', 'true')))
    T.truthy(C.Set('my.name', 'abc'))
    T.isnil((C.Set('my.name', 'toolong')))
    T.isnil((C.Set('my.name', 5)))
  end)

  T.it('values are stored in the profile as nested tables (Contracts F5)', function()
    local _, _, ns, C = boot()
    C.Set('prune.days', 30)
    C.Set('idleSec', 200)
    local profile = ns.Store.Section('profile')
    T.eq(profile.prune.days, 30)
    T.eq(profile.idleSec, 200)
  end)

  T.it('Reset removes the stored value and prunes empty parent tables', function()
    local _, _, ns, C = boot()
    C.Set('prune.days', 30)
    T.truthy(C.Reset('prune.days'))
    T.eq(C.Get('prune.days'), 90)
    T.isnil(ns.Store.Section('profile').prune)
    C.Set('prune.days', 30); C.Set('prune.maxBytes', 500000)
    C.Reset('prune.days')
    T.eq(ns.Store.Section('profile').prune.maxBytes, 500000, 'sibling keys survive')
  end)

  T.it('ResetAll resets every changed setting and returns how many', function()
    local _, _, _, C = boot()
    C.Set('idleSec', 200); C.Set('minSegSec', 900)
    T.eq(C.ResetAll(), 2)
    T.eq(C.Get('idleSec'), 120)
    T.eq(C.Get('heatGrid'), 32)
  end)

  T.it('unknown keys already saved in the profile are preserved', function()
    local _, _, ns, C = boot(function(W)
      W.env.GoldIntelDB = { schema = 1, profile = { futureSetting = 'keep me', ui = { scale = 2 } } }
    end)
    C.Set('idleSec', 200)
    C.ResetAll()
    local profile = ns.Store.Section('profile')
    T.eq(profile.futureSetting, 'keep me')
    T.eq(profile.ui.scale, 2)
  end)

  T.it('Load ignores invalid saved values (the default applies) and reports them', function()
    local _, P, _, C = boot(function(W)
      W.env.GoldIntelDB = { schema = 1, profile = { idleSec = 'lots', prune = { days = -5 }, minSegSec = 700 } }
    end)
    T.eq(C.Get('idleSec'), 120)
    T.eq(C.Get('prune.days'), 90)
    T.eq(C.Get('minSegSec'), 700)
    local report = C.Load()
    T.truthy(report.invalid.idleSec)
    T.truthy(report.invalid['prune.days'])
    T.isnil(report.invalid.minSegSec)
    local warned = false
    for _, d in ipairs(P.GetDiag()) do
      if d.level == 'warn' and d.msg:find('invalid saved value for idleSec', 1, true) then warned = true end
    end
    T.truthy(warned)
  end)

  T.it('Parse converts command text to typed values', function()
    local _, _, _, C = boot()
    T.eq(C.Parse('idleSec', '150'), 150)
    T.eq(C.Parse('defaultSellThrough', '0.25'), 0.25)
    T.isnil((C.Parse('idleSec', 'abc')))
    C.Define('my.flag', { type = 'boolean', default = false })
    T.eq(C.Parse('my.flag', 'on'), true)
    T.eq(C.Parse('my.flag', 'YES'), true)
    T.eq(C.Parse('my.flag', '0'), false)
    T.eq(C.Parse('my.flag', 'off'), false)
    T.isnil((C.Parse('my.flag', 'maybe')))
    T.eq(C.Parse('valuation', 'conservative'), 'conservative')
    T.isnil((C.Parse('nope', '1')))
  end)
end)

T.describe('Config change notification and persistence flag', function()
  T.it('fires CONFIG_CHANGED with value, previous and source; silent when unchanged', function()
    local _, _, ns, C = boot()
    local seen = {}
    ns.Bus.On('CONFIG_CHANGED', function(p) seen[#seen + 1] = p.key .. ':' .. tostring(p.previous) .. '->' .. tostring(p.value) .. '/' .. p.source end)
    C.Set('idleSec', 200, 'command')
    C.Set('idleSec', 200, 'command')
    C.Reset('idleSec')
    C.Reset('idleSec')
    T.eq(seen, { 'idleSec:120->200/command', 'idleSec:200->120/reset' })
  end)

  T.it('Set reports persisted = true when the database is writable', function()
    local _, _, _, C = boot()
    local ok, persisted = C.Set('idleSec', 200)
    T.truthy(ok); T.eq(persisted, true)
  end)

  T.it('with a read-only database the value works this session but is not persisted', function()
    local live = { schema = 99, profile = { idleSec = 777 } }
    local _, _, ns, C = boot(function(W) W.env.GoldIntelDB = live end)
    T.eq(ns.Store.Status().state, 'readonly')
    local ok, persisted = C.Set('idleSec', 200)
    T.truthy(ok); T.eq(persisted, false)
    T.eq(C.Get('idleSec'), 200)
    T.eq(live.profile.idleSec, 777, 'the saved file data is untouched')
  end)

  T.it('without a store the setters report an error and Get falls back to defaults', function()
    local W, _, ns = Loader.boot({}, { only = { 'Platform/Platform.lua', 'Platform/Clock.lua', 'Core/Core.lua', 'Core/Bus.lua', 'Core/Config.lua' } })
    local C = ns.Config
    T.eq(C.Get('idleSec'), 120)
    local ok, err = C.Set('idleSec', 200)
    T.isnil(ok); T.truthy(err:find('store is not available', 1, true))
  end)
end)
