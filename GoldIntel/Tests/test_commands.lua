T.describe('Commands API', function()
  T.it('Register validates and rejects duplicates; modules can add commands', function()
    local _, _, ns, run = boot()
    local C = ns.Commands
    T.truthy(C.Register('hello', { help = 'says hi', fn = function() ns.Platform.Print('hi from module') end }))
    T.isnil((C.Register('hello', { fn = function() end })))
    T.isnil((C.Register('Bad Name', { fn = function() end })))
    T.isnil((C.Register('x', {})))
    T.isnil((C.Register('x', 'fn')))
    T.truthy(run('hello'):find('hi from module', 1, true))
    T.truthy(run('help'):find('hello', 1, true))
  end)

  T.it('a failing command is caught and reported', function()
    local _, P, ns, run = boot()
    ns.Commands.Register('explode', { fn = function() error('command bug') end })
    local out = run('explode')
    T.truthy(out:find('command failed', 1, true))
    local logged = false
    for _, d in ipairs(P.GetDiag()) do if d.msg:find('command bug', 1, true) then logged = true end end
    T.truthy(logged)
  end)

  T.it('Names is sorted and complete', function()
    local _, _, ns = boot()
    T.eq(ns.Commands.Names(), { 'activity', 'afk', 'agg', 'caps', 'checkpoint', 'collect', 'config', 'db', 'debug', 'diag', 'help', 'ledger', 'lots', 'modules', 'pause', 'perf', 'price', 'probe', 'resume', 'settings', 'status', 'version' })
  end)
end)
