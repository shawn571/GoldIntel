--[[
Tests / test_commands.lua                                    (Phase 2: Core/Slash.lua)

The /gi command set as a user sees it.
]]

local T = require('testlib')
local Loader = require('loader')

local function boot(fakeOpts, preload)
  local Fake = require('fake_wow')
  local W = Fake.new(fakeOpts)
  if preload then preload(W) end
  local P, ns = Loader.load(W.env)
  W:login()
  local function run(text)
    W.printed = {}
    W.env.SlashCmdList.GOLDINTEL(text)
    return W:printedText()
  end
  return W, P, ns, run
end

T.describe('/gi summary, help, version, status', function()
  T.it('the bare command prints the product summary', function()
    local _, _, _, run = boot()
    local out = run('')
    T.truthy(out:find('GoldIntel 0.6.2-passive', 1, true))
    T.truthy(out:find('operational=true', 1, true))
    T.truthy(out:find('core=ready', 1, true))
    T.truthy(out:find('store=migrated schema=2 writable=true', 1, true))
    T.truthy(out:find('events: registered=', 1, true))
    T.truthy(out:find('/gi help', 1, true))
  end)

  T.it('help lists every command with its usage', function()
    local _, _, _, run = boot()
    local out = run('help')
    for _, name in ipairs({ 'status', 'version', 'probe', 'diag', 'debug', 'caps', 'config', 'db', 'modules', 'checkpoint' }) do
      T.truthy(out:find(name, 1, true), name)
    end
    T.truthy(out:find('config [list|get K|set K V|reset K|all]', 1, true))
  end)

  T.it('status keeps the Phase 1 line and adds core and store lines', function()
    local _, _, _, run = boot()
    local out = run('status')
    T.truthy(out:find('operational=true ready=true inWorld=true scheduler=ctimer', 1, true))
    T.truthy(out:find('lastRegister=PLAYER_MONEY', 1, true))
    T.truthy(out:find('core=ready modules=5 enabled=5 failed=0 disabled=0 stubs=2', 1, true))
    T.truthy(out:find('store=migrated schema=2 writable=true size~', 1, true))
  end)

  T.it('version shows addon, contract, client build and interface', function()
    local _, _, _, run = boot()
    local out = run('version')
    T.truthy(out:find('0.6.2-passive', 1, true))
    T.truthy(out:find('contract 1.17.0', 1, true))
    T.truthy(out:find('build 61000', 1, true))
    T.truthy(out:find('interface 11509', 1, true))
  end)

  T.it('commands are case-insensitive; unknown ones are reported', function()
    local _, _, _, run = boot()
    T.truthy(run('STATUS'):find('operational=', 1, true))
    T.truthy(run('  Help  '):find('commands', 1, true))
    T.truthy(run('bogus'):find('unknown command "bogus"', 1, true))
    T.truthy(run(nil):find('GoldIntel', 1, true))
  end)
end)

T.describe('/gi probe, diag, debug', function()
  T.it('probe prints the report, persists it and refreshes capabilities', function()
    local W, _, ns, run = boot()
    local out = run('probe')
    T.truthy(out:find('GoldIntel probe report', 1, true))
    T.truthy(out:find('[ok]      money.get', 1, true))
    T.truthy(out:find('/reload or logout', 1, true))
    T.truthy(W.env.GoldIntelDB.compat.report)
    T.eq(ns.Capabilities.Level('map.cmap'), 'present')
  end)

  T.it('diag prints recent diagnostics or says there are none', function()
    local _, P, _, run = boot()
    P.ClearDiag()
    T.truthy(run('diag'):find('no diagnostics', 1, true))
    P.Diag('warn', 'Test', 'something odd')
    T.truthy(run('diag'):find('warn [Test] something odd', 1, true))
  end)

  T.it('debug toggles the event echo and tick echo', function()
    local _, P, _, run = boot()
    run('debug on');    T.truthy(P.debug)
    run('debug off');   T.falsy(P.debug)
    run('debug ticks'); T.truthy(P.debugTicks)
    run('debug ticks'); T.falsy(P.debugTicks)
  end)

  T.it('debug ticks warns when the event echo is still off', function()
    local _, P, _, run = boot()
    T.truthy(run('debug ticks'):find('/gi debug on', 1, true))
    run('debug on')
    run('debug ticks')   -- off again
    local out = run('debug ticks')   -- on, with debug already on
    T.truthy(out:find('tick echo on', 1, true))
    T.falsy(out:find('nothing is echoed', 1, true))
  end)
end)

T.describe('/gi caps', function()
  T.it('shows the stages of each event capability and the rule for depending on one', function()
    local _, _, _, run = boot()
    local out = run('caps')
    T.truthy(out:find('events: delivered=2 registered=10', 1, true), 'login events were delivered, the other ten are only registered')
    T.truthy(out:find('event.PLAYER_MONEY  [registered]  valid=yes registered=yes delivered=not-seen-yet payloadUsable=unknown', 1, true))
    T.truthy(out:find('Only payloadUsable', 1, true))
    T.truthy(out:find('not-seen-yet / unknown = not observed yet (not a failure)', 1, true))
  end)

  T.it('after a money event the same capability shows delivered and usable payload', function()
    local W, _, _, run = boot()
    W.state.money = 10; W:fire('PLAYER_MONEY')
    local out = run('caps money')
    T.truthy(out:find('event.PLAYER_MONEY  [payloadUsable]  valid=yes registered=yes delivered=yes payloadUsable=yes', 1, true))
  end)

  T.it('filters: events, api, all and free text', function()
    local _, _, _, run = boot()
    T.truthy(run('caps api'):find('map.cmap  [present]', 1, true))
    T.truthy(run('caps api'):find('mail.api  [absent]', 1, true))
    T.truthy(run('caps api'):find('combatlog.event  [unknown]', 1, true))
    T.falsy(run('caps events'):find('map.cmap', 1, true))
    T.truthy(run('caps all'):find('map.cmap', 1, true))
    T.truthy(run('caps all'):find('event.PLAYER_LOGIN', 1, true))
    T.truthy(run('caps zone'):find('event.ZONE_CHANGED', 1, true))
  end)
end)

T.describe('/gi config', function()
  T.it('lists settings with defaults and read-only markers', function()
    local _, _, _, run = boot()
    local out = run('config')
    T.truthy(out:find('idleSec = 120', 1, true))
    T.truthy(out:find('heatGrid = 32  [read-only]', 1, true))
    T.truthy(out:find('prune.days = 90', 1, true))
  end)

  T.it('set, get and reset round-trip and persist into the profile', function()
    local W, _, ns, run = boot()
    T.truthy(run('config set idleSec 200'):find('idleSec = 200', 1, true))
    T.truthy(run('config get idleSec'):find('idleSec = 200', 1, true))
    T.eq(W.env.GoldIntelDB.profile.idleSec, 200)
    T.truthy(run('config'):find('idleSec = 200   (default 120)', 1, true))
    T.truthy(run('config reset idleSec'):find('idleSec reset to 120', 1, true))
    T.isnil(W.env.GoldIntelDB.profile.idleSec)
    run('config set prune.days 30'); run('config set minSegSec 900')
    T.truthy(run('config reset all'):find('reset 2 setting', 1, true))
    T.eq(ns.Config.Get('prune.days'), 90)
  end)

  T.it('bad input gets a helpful message and changes nothing', function()
    local _, _, ns, run = boot()
    T.truthy(run('config set idleSec abc'):find('needs a number', 1, true))
    T.truthy(run('config set idleSec 5'):find('at least 10', 1, true))
    T.truthy(run('config set heatGrid 32'):find('read-only', 1, true))
    T.truthy(run('config set nope 1'):find('unknown setting', 1, true))
    T.truthy(run('config get nope'):find('unknown setting', 1, true))
    T.truthy(run('config set idleSec'):find('usage', 1, true))
    T.truthy(run('config get'):find('usage', 1, true))
    T.truthy(run('config reset'):find('usage', 1, true))
    T.truthy(run('config frobnicate'):find('usage', 1, true))
    T.eq(ns.Config.Get('idleSec'), 120)
  end)

  T.it('with a read-only database a set says it lasts this session only', function()
    local _, _, _, run = boot(nil, function(W) W.env.GoldIntelDB = { schema = 99 } end)
    T.truthy(run('config set idleSec 200'):find('this session only', 1, true))
  end)
end)

