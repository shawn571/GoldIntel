--[[
Tests / test_platform.lua                                  (task 1.2: Platform.lua)

Capability registry, diagnostics ring buffer, lifecycle (ready / fatal), utilities.
Only Platform.lua is loaded here (plus nothing else) so failures point at this file.
]]

local T = require('testlib')
local Loader = require('loader')

local function bootCore()
  return Loader.boot({}, { only = { 'Platform/Platform.lua' } })
end

T.describe('Platform.Util', function()
  local _, P = bootCore()

  T.it('shallowCopy copies and is nil-safe', function()
    local src = { a = 1, b = 2 }
    local copy = P.Util.shallowCopy(src)
    T.eq(copy, src)
    copy.a = 99
    T.eq(src.a, 1)
    T.eq(P.Util.shallowCopy(nil), {})
  end)

  T.it('sortedKeys orders numbers before strings, each ascending', function()
    T.eq(P.Util.sortedKeys({ b = 1, a = 1, [2] = 1, [1] = 1 }), { 1, 2, 'a', 'b' })
  end)

  T.it('shallowEqual compares keys and values', function()
    T.truthy(P.Util.shallowEqual({ a = 1 }, { a = 1 }))
    T.falsy(P.Util.shallowEqual({ a = 1 }, { a = 2 }))
    T.falsy(P.Util.shallowEqual({ a = 1 }, { a = 1, b = 2 }))
    T.falsy(P.Util.shallowEqual({ a = 1, b = 2 }, { a = 1 }))
    T.truthy(P.Util.shallowEqual({}, {}))
    T.falsy(P.Util.shallowEqual({}, nil))
  end)
end)

T.describe('capability registry', function()
  T.it('unknown capabilities are not available', function()
    local _, P = bootCore()
    T.falsy(P.Has('nothing.here'))
  end)

  T.it('SetCap coerces to boolean, stores notes, and Has reflects it', function()
    local _, P = bootCore()
    T.eq(P.SetCap('x.y', 1, 'note'), true)
    T.truthy(P.Has('x.y'))
    T.eq(P.CapNote('x.y'), 'note')
    P.SetCap('x.y', nil)
    T.falsy(P.Has('x.y'))
    T.eq(P.CapNote('x.y'), 'note', 'a nil note must not erase the previous note')
  end)

  T.it('Capabilities returns a copy', function()
    local _, P = bootCore()
    P.SetCap('a', true)
    local copy = P.Capabilities()
    copy.a = false
    T.truthy(P.Has('a'))
  end)

  T.it('watchers fire only on change and failures are isolated', function()
    local _, P = bootCore()
    local seen = {}
    P.WatchCaps(function() error('boom') end)
    P.WatchCaps(function(cap, value, previous) seen[#seen + 1] = { cap, value, previous } end)
    P.SetCap('c', true)
    P.SetCap('c', true)              -- no change
    P.SetCap('c', false)
    T.eq(seen, { { 'c', true, nil }, { 'c', false, true } })
    T.truthy(P.DiagCount() >= 2, 'watcher failures are reported as diagnostics')
  end)

  T.it('WatchCaps rejects non-functions', function()
    local _, P = bootCore()
    local ok, err = P.WatchCaps('nope')
    T.isnil(ok)
    T.truthy(err)
  end)
end)

T.describe('diagnostics', function()
  T.it('keeps entries in order with level, module and message', function()
    local _, P = bootCore()
    P.Diag('info', 'Mod', 'first')
    P.Diag('warn', 'Mod', 'second')
    local list = P.GetDiag()
    T.eq(#list, 2)
    T.eq(list[1].msg, 'first')
    T.eq(list[2].level, 'warn')
    T.eq(list[2].module, 'Mod')
  end)

  T.it('unknown levels fall back to info', function()
    local _, P = bootCore()
    P.Diag('chatty', 'M', 'x')
    T.eq(P.GetDiag()[1].level, 'info')
  end)

  T.it('ring buffer keeps the newest 200 entries, oldest first', function()
    local _, P = bootCore()
    for i = 1, 250 do P.Diag('debug', 'M', 'm' .. i) end
    local list = P.GetDiag()
    T.eq(#list, 200)
    T.eq(list[1].msg, 'm51')
    T.eq(list[200].msg, 'm250')
    T.eq(P.DiagCount(), 250)
  end)

  T.it('errors are printed once per unique message; warnings are silent unless debug', function()
    local W, P = bootCore()
    P.Diag('error', 'M', 'same')
    P.Diag('error', 'M', 'same')
    P.Diag('warn', 'M', 'quiet')
    T.eq(#W.printed, 1)
    P.SetDebug(true)
    P.Diag('warn', 'M', 'loud')
    T.eq(#W.printed, 2)
  end)

  T.it('sink receives every entry and a failing sink never breaks Diag', function()
    local _, P = bootCore()
    local got = {}
    P.SetDiagSink(function(entry) got[#got + 1] = entry.msg end)
    P.Diag('info', 'M', 'a')
    P.SetDiagSink(function() error('sink broke') end)
    P.Diag('info', 'M', 'b')           -- must not raise
    T.eq(got, { 'a' })
    T.eq(P.DiagCount(), 2)
    local ok, err = P.SetDiagSink('bad')
    T.isnil(ok)
    T.truthy(err)
  end)

  T.it('ClearDiag empties the buffer', function()
    local _, P = bootCore()
    P.Diag('info', 'M', 'a')
    P.ClearDiag()
    T.eq(P.GetDiag(), {})
    T.eq(P.DiagCount(), 0)
  end)

  T.it('Print is silent when print is unavailable', function()
    local _, P = Loader.boot({ without = { 'print' } }, { only = { 'Platform/Platform.lua' } })
    P.Print('hello')                   -- must not raise
    P.Diag('error', 'M', 'x')
  end)
end)

T.describe('lifecycle', function()
  T.it('OnReady queues until MarkReady, then runs in registration order', function()
    local _, P = bootCore()
    local order = {}
    P.OnReady(function() order[#order + 1] = 1 end)
    P.OnReady(function() order[#order + 1] = 2 end)
    T.falsy(P.IsReady())
    T.truthy(P.MarkReady())
    T.eq(order, { 1, 2 })
    T.truthy(P.IsReady())
  end)

  T.it('MarkReady is idempotent', function()
    local _, P = bootCore()
    local n = 0
    P.OnReady(function() n = n + 1 end)
    P.MarkReady()
    T.falsy(P.MarkReady())
    T.eq(n, 1)
  end)

  T.it('OnReady after ready runs immediately', function()
    local _, P = bootCore()
    P.MarkReady()
    local ran = false
    P.OnReady(function() ran = true end)
    T.truthy(ran)
  end)

  T.it('a failing ready listener does not block the others', function()
    local _, P = bootCore()
    local ran = false
    P.OnReady(function() error('bad listener') end)
    P.OnReady(function() ran = true end)
    P.MarkReady()
    T.truthy(ran)
    T.truthy(P.DiagCount() >= 1)
  end)

  T.it('OnReady and OnFatal reject non-functions', function()
    local _, P = bootCore()
    T.isnil((P.OnReady('x')))
    T.isnil((P.OnFatal('x')))
  end)
end)

T.describe('fatal handling', function()
  T.it('first fatal wins and listeners are notified once', function()
    local _, P = bootCore()
    local calls = {}
    P.OnFatal(function(reason, cap) calls[#calls + 1] = { reason, cap } end)
    T.truthy(P.Fatal('money.get', 'no money'))
    T.falsy(P.Fatal('frame', 'second'))
    T.falsy(P.IsOperational())
    T.eq(P.fatalCap, 'money.get')
    T.eq(P.fatalReason, 'no money')
    T.eq(calls, { { 'no money', 'money.get' } })
  end)

  T.it('CheckFatal passes only when every fatal capability is available', function()
    local _, P = bootCore()
    P.SetCap('frame', true)
    P.SetCap('money.get', true)
    T.falsy(P.CheckFatal(), 'money.event is still unknown')
    T.falsy(P.IsOperational())
  end)

  T.it('CheckFatal keeps the platform operational when all are present', function()
    local _, P = bootCore()
    P.SetCap('frame', true)
    P.SetCap('money.get', true)
    P.SetCap('money.event', true)
    T.truthy(P.CheckFatal())
    T.truthy(P.IsOperational())
  end)

  T.it('SafeCall reports failures as diagnostics instead of raising', function()
    local _, P = bootCore()
    local ok = P.SafeCall('M', function() error('x') end)
    T.falsy(ok)
    T.eq(P.GetDiag()[1].level, 'error')
    local ok2, value = P.SafeCall('M', function(a) return a * 2 end, 21)
    T.truthy(ok2)
    T.eq(value, 42)
  end)
end)

T.describe('event safety helpers (D-025)', function()
  T.it('EventNameValid reports true/false from C_EventUtils and never registers', function()
    local W, P = bootCore()
    W.state.invalidEvents.BAD_EVENT = true
    T.eq(P.EventNameValid('GOOD_EVENT'), true)
    T.eq(P.EventNameValid('BAD_EVENT'), false)
    T.eq(#W.registerCalls, 0)
  end)

  T.it('EventNameValid is nil (unknown) without C_EventUtils or when it raises', function()
    local _, P = Loader.boot({ without = { 'C_EventUtils' } }, { only = { 'Platform/Platform.lua' } })
    T.isnil(P.EventNameValid('X'))
    local W2, P2 = bootCore()
    W2.env.C_EventUtils.IsEventValid = function() error('api broke') end
    T.isnil(P2.EventNameValid('X'))
  end)

  T.it('the combat log event is on the restricted list by default', function()
    local _, P = bootCore()
    T.truthy(P.RESTRICTED_EVENTS.COMBAT_LOG_EVENT_UNFILTERED)
  end)

  T.it('IsSecret follows issecretvalue and is false when the API is missing or raises', function()
    local W, P = bootCore()
    T.falsy(P.IsSecret(5))
    W.env.issecretvalue = function(v) return v == 'SECRET' end
    T.truthy(P.IsSecret('SECRET'))
    T.falsy(P.IsSecret('public'))
    W.env.issecretvalue = function() error('boom') end
    T.falsy(P.IsSecret('SECRET'))
  end)
end)

T.describe('output recording (chat lines kept for the saved data)', function()
  T.it('Print records each line with a timestamp, still prints, and survives a missing print', function()
    local W, P = bootCore()
    P.Print('first line')
    P.Print('second line')
    local out = P.GetOutput()
    T.eq(#out, 2)
    T.truthy(out[1]:match('^%d+ first line$'))
    T.truthy(out[2]:match('^%d+ second line$'))
    T.eq(P.OutputCount(), 2)
    T.truthy(W:printedText():find('GoldIntel: first line', 1, true))
    local _, P2 = Loader.boot({ without = { 'print' } }, { only = { 'Platform/Platform.lua' } })
    P2.Print('silent client')
    T.eq(#P2.GetOutput(), 1)
  end)

  T.it('GetOutput(n) returns the newest n lines oldest first; the ring keeps 200', function()
    local _, P = bootCore()
    for i = 1, 250 do P.Print('line ' .. i) end
    local last3 = P.GetOutput(3)
    T.truthy(last3[1]:find('line 248', 1, true) and last3[3]:find('line 250', 1, true))
    T.eq(#P.GetOutput(), 200)
    T.eq(P.OutputCount(), 250)
    T.truthy(P.GetOutput()[1]:find('line 51', 1, true))
    P.ClearOutput()
    T.eq(#P.GetOutput(), 0)
  end)

  T.it('errors reported through Diag are part of the recorded output', function()
    local _, P = bootCore()
    P.Diag('error', 'M', 'recorded problem')
    T.truthy(P.GetOutput()[1]:find('recorded problem', 1, true))
  end)
end)
