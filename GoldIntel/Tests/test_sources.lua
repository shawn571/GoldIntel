local T = require('testlib')
local World = require('collectworld')
local L = require('ledgerworld')

local function entries(ns) return ns.Sources.Entries() end

local function coinLoot(W, guid, amounts)
  local slots = {}
  for i, a in ipairs(amounts) do slots[i] = { type = 2, amount = a } end
  W.state.loot = { guid = guid or 'Creature-0-4621-0-1-95-AAAA', slots = slots }
  W:fire('LOOT_OPENED')
end

T.describe('Sources lifecycle', function()
  T.it('nothing is recorded before Begin and after End', function()
    local W, _, ns = World.boot()
    ns.Collector.On({}); ns.Ledger.End()      -- collect on starts the ledger interval; these tests start Sources by hand
    L.pay(W, 50); W:advance(2)
    T.eq(#entries(ns), 0)
    ns.Sources.Begin(); W:advance(0.6)
    L.pay(W, 7); W:advance(2)
    T.eq(#entries(ns), 1)
    T.truthy(ns.Sources.End())
    L.pay(W, 9); W:advance(2)
    T.eq(#entries(ns), 1)
    T.falsy(ns.Sources.End())
  end)

  T.it('End turns a pending delta into OTHER at once and ends the ticker', function()
    local W, _, ns = L.boot()
    L.pay(W, 12)
    ns.Sources.End()
    T.eq(#entries(ns), 1); T.eq(entries(ns)[1].src, 'other')
    T.truthy(ns.Sources.Stats().sumDeltas == 12)
  end)

  T.it('Begin twice is a no-op; a handler error is contained and counted', function()
    local _, _, ns = L.boot()
    T.falsy(ns.Sources.Begin())
    T.eq(ns.Sources.Stats().sources.handlerErrors, 0)
  end)

  T.it('unexplained money becomes OTHER after WAIT (2.0 s, M5) with low confidence', function()
    local W, _, ns = L.boot()
    L.pay(W, 33); W:advance(1.5)
    T.eq(#entries(ns), 0)
    W:advance(0.7)
    local e = entries(ns)[1]
    T.eq(e.src, 'other'); T.eq(e.conf, 'low'); T.eq(e.copper, 33); T.eq(e.act, 'OTHER')
  end)

  T.it('a gap (money changed without PLAYER_MONEY) becomes an OTHER entry flagged gap', function()
    local W, P, ns = L.boot()
    W.state.money = W.state.money + 500
    P.MoneyModule.Sync(true)
    W:advance(0.1)
    local e = entries(ns)[1]
    T.eq(e.src, 'other'); T.eq(e.comp, 'gap'); T.eq(e.copper, 500)
    local s = ns.Sources.Stats()
    T.eq(s.gapCount, 1); T.eq(s.gapValue, 500)
  end)
end)

T.describe('Sources: loot coin', function()
  T.it('creature coin: exact match, loot, high, GRIND, creditable with a fresh location', function()
    local W, _, ns = L.boot()
    coinLoot(W, nil, { 8 })
    W:advance(0.378); L.pay(W, 8); W:advance(0.2)
    local e = entries(ns)[1]
    T.eq(#entries(ns), 1)
    T.eq(e.src, 'loot'); T.eq(e.conf, 'high'); T.eq(e.copper, 8); T.eq(e.act, 'GRIND')
    T.eq(e.locConf, 'fresh'); T.truthy(e.creditable); T.eq(e.ref.sourceType, 'creature')
  end)

  T.it('the expectation is held while the loot window stays open (a slow loot, 9 s)', function()
    local W, _, ns = L.boot()
    coinLoot(W, nil, { 11 })
    W:advance(9.0)
    T.truthy(ns.Context.IsActive('loot'))
    L.pay(W, 11); W:advance(0.3)
    T.eq(entries(ns)[1].src, 'loot')
    W.state.lootShown = false; W:advance(2.0)
    T.eq(ns.Sources.Stats().unmatched, 0)
  end)

  T.it('walking away: money 0.5 s after the window closed still matches; 2.6 s later is OTHER', function()
    local W, _, ns = L.boot()
    coinLoot(W, nil, { 6 })
    W.state.lootShown = false; W:advance(0.2)
    W:advance(0.5); L.pay(W, 6); W:advance(0.1)
    T.eq(entries(ns)[1].src, 'loot')
    coinLoot(W, nil, { 9 })
    W.state.lootShown = false; W:advance(2.6)
    L.pay(W, 9); W:advance(2.3)
    T.eq(entries(ns)[2].src, 'other')
    T.eq(ns.Sources.Stats().unmatched, 1)
  end)

  T.it('two coin slots paid in one money event give two entries; paid separately give two entries', function()
    local W, _, ns = L.boot()
    coinLoot(W, nil, { 8, 5 })
    W:advance(0.4); L.pay(W, 13); W:advance(0.3)
    T.eq(#entries(ns), 2); T.eq(L.sum(entries(ns)), 13)
    T.eq(entries(ns)[1].src, 'loot'); T.eq(entries(ns)[2].src, 'loot')
    coinLoot(W, nil, { 8, 5 })
    W:advance(0.4); L.pay(W, 8); W:advance(0.1); L.pay(W, 5); W:advance(0.3)
    T.eq(#entries(ns), 4); T.eq(ns.Sources.Stats().bySource.loot.copper, 26)
  end)

  T.it('game-object loot after a herb cast is GATHER high; without a cast it is OTHER activity', function()
    local W, P, ns = L.boot()
    P.Unit.ResetCasts()
    W:fire('UNIT_SPELLCAST_SUCCEEDED', 'player', 'c', 2366)
    W:advance(2); coinLoot(W, 'GameObject-0-6782-0-4-1731-X', { 4 })
    W:advance(0.3); L.pay(W, 4); W:advance(0.2)
    local e = entries(ns)[1]
    T.eq(e.src, 'loot'); T.eq(e.act, 'GATHER'); T.eq(e.actConf, 'high'); T.truthy(e.creditable)
    P.Unit.ResetCasts()
    W.state.lootShown = false; W:advance(2)
    coinLoot(W, 'GameObject-0-6782-0-4-1731-X', { 4 })
    W:advance(0.3); L.pay(W, 4); W:advance(0.2)
    T.eq(entries(ns)[2].act, 'OTHER')
  end)

  T.it('item-container (Item) coin is loot but not creditable', function()
    local W, _, ns = L.boot()
    coinLoot(W, 'Item-4618-0-400000008C56C916', { 20 })
    W:advance(0.3); L.pay(W, 20); W:advance(0.2)
    T.eq(entries(ns)[1].src, 'loot'); T.falsy(entries(ns)[1].creditable)
  end)

  T.it('no location stamp yet means creditable is false', function()
    local W, _, ns = L.boot({ noTick = true })
    coinLoot(W, nil, { 8 })
    L.pay(W, 8); W:advance(0.1)
    local e = entries(ns)[1]
    T.eq(e.src, 'loot'); T.eq(e.locConf, 'none'); T.falsy(e.creditable)
  end)
end)

