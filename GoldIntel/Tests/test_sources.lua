T.describe('Sources: vendor and trade windows', function()
  T.it('a sale inside the vendor window is vendor/med, a payment is purchase/med', function()
    local W, _, ns = L.boot()
    W:fire('MERCHANT_SHOW'); W:advance(3)
    L.pay(W, 60); W:advance(0.1); L.pay(W, -10); W:advance(0.1)
    W:fire('MERCHANT_CLOSED'); W:advance(0.3)
    local a, b = entries(ns)[1], entries(ns)[2]
    T.eq(a.src, 'vendor'); T.eq(a.conf, 'med'); T.eq(a.act, 'VENDOR'); T.eq(a.copper, 60)
    T.eq(b.src, 'purchase'); T.eq(b.conf, 'med'); T.eq(b.copper, -10)
  end)
  T.it('vendor money 0.9 s after the close is still vendor, 1.5 s after is OTHER', function()
    local W, _, ns = L.boot()
    W:fire('MERCHANT_SHOW'); W:advance(1); W:fire('MERCHANT_CLOSED')
    W:advance(0.9); L.pay(W, 7); W:advance(0.1)
    T.eq(entries(ns)[1].src, 'vendor')
    W:advance(1.5); L.pay(W, 8); W:advance(2.2)
    T.eq(entries(ns)[2].src, 'other')
  end)
  T.it('trade money both ways is trade/med 0.394 s after the doubled close (E-31)', function()
    local W, _, ns = L.boot()
    W:fire('TRADE_SHOW'); W:advance(5)
    W:fire('TRADE_CLOSED'); W:fire('TRADE_CLOSED')
    W:advance(0.394); L.pay(W, -10); W:advance(0.2)
    local e = entries(ns)[1]
    T.eq(e.src, 'trade'); T.eq(e.conf, 'med'); T.eq(e.copper, -10); T.eq(e.act, 'TRADE')
    W:fire('TRADE_SHOW'); W:advance(2); L.pay(W, 5); W:advance(0.1); W:fire('TRADE_CLOSED'); W:advance(1.5)
    T.eq(entries(ns)[2].src, 'trade'); T.eq(entries(ns)[2].copper, 5)
  end)
  T.it('a cancelled trade (zero money move) creates no entry', function()
    local W, _, ns = L.boot()
    W:fire('TRADE_SHOW'); W:advance(1); W:fire('TRADE_CLOSED'); W:advance(0.4)
    W:fire('PLAYER_MONEY'); W:advance(2)
    T.eq(#entries(ns), 0)
  end)
  T.it('vendor and trade open together: the higher priority (trade) wins with LOW confidence', function()
    local W, _, ns = L.boot()
    W:fire('MERCHANT_SHOW'); W:fire('TRADE_SHOW'); W:advance(1)
    L.pay(W, 20); W:advance(0.1)
    local e = entries(ns)[1]
    T.eq(e.src, 'trade'); T.eq(e.conf, 'low')
  end)
  T.it('a loot coin equal to the delta wins over an open vendor window (exact before window)', function()
    local W, _, ns = L.boot()
    W:fire('MERCHANT_SHOW'); W:advance(0.5)
    coinLoot(W, nil, { 12 })
    W:advance(0.3); L.pay(W, 12); W:advance(0.2)
    T.eq(entries(ns)[1].src, 'loot')
  end)
  T.it('collect on inside an already open vendor window still gives it a window', function()
    local W, _, ns = World.boot()
    ns.Collector.On({}); ns.Ledger.End()      -- collect on starts the ledger interval; these tests start Sources by hand
    W:fire('MERCHANT_SHOW'); W:advance(1)
    ns.Sources.Begin(); W:advance(0.3)
    L.pay(W, 40); W:advance(0.1)
    T.eq(entries(ns)[1].src, 'vendor')
  end)
end)

T.describe('Sources: mail', function()
  local function open(W) W.state.mailShown = true; W:advance(1.0) end

  T.it('the first update after the mailbox opened is a baseline only', function()
    local W, _, ns = L.boot()
    open(W)
    L.inbox(W, { L.moneyMail(44) })
    W:advance(0.3)
    T.eq(ns.Sources.Stats().sources.mailBaselines, 1); T.eq(ns.Sources.Stats().sources.mailExp, 0)
  end)

  T.it('taking a money mail: mailMoney, exact, high, settle, MAIL (E-28: money 0.365 s after the update)', function()
    local W, _, ns = L.boot()
    open(W)
    L.inbox(W, { L.moneyMail(44) }); W:advance(1.0)
    L.inbox(W, {}); W:advance(0.365); L.pay(W, 44); W:advance(0.2)
    local e = entries(ns)[1]
    T.eq(#entries(ns), 1)
    T.eq(e.src, 'mailMoney'); T.eq(e.conf, 'high'); T.truthy(e.settle); T.eq(e.act, 'MAIL'); T.falsy(e.creditable)
  end)

  T.it('COD payment mail is codIn (E-40: +100 exact, 0.267 s after the update)', function()
    local W, _, ns = L.boot()
    open(W)
    L.inbox(W, { L.moneyMail(100, 'COD Payment: Spider Ichor (4)', 'Divine Slaps') }); W:advance(1.0)
    L.inbox(W, {}); W:advance(0.267); L.pay(W, 100); W:advance(0.2)
    local e = entries(ns)[1]
    T.eq(e.src, 'codIn'); T.eq(e.copper, 100); T.truthy(e.settle); T.eq(e.conf, 'high')
  end)

  T.it('AH sale mail splits 149 into 51 / -2 / +100 (E-34), components sum to the delta', function()
    local W, _, ns = L.boot()
    open(W)
    L.inbox(W, { L.saleMail(51, 100, 2) }); W:advance(1.0)
    L.inbox(W, {}); W:advance(0.3); L.pay(W, 149); W:advance(0.2)
    local es = entries(ns)
    T.eq(#es, 3)
    T.eq({ es[1].src, es[1].copper, es[1].settle }, { 'ahSale', 51, true })
    T.eq({ es[2].src, es[2].copper }, { 'ahCut', -2 })
    T.eq({ es[3].src, es[3].copper, es[3].comp }, { 'ahDepositRefund', 100, 'deposit' })
    T.eq(L.sum(es), 149)
    for _, e in ipairs(es) do T.eq(e.conf, 'high') end
    T.truthy(ns.Sources.Reconciler():Check())
  end)

  T.it('a sale with zero cut or zero deposit omits the zero component', function()
    local _, _, ns = L.boot()
    local spec = ns.Sources.MailSpec({ money = 50, cod = 0, subject = 's', invoice = { kind = 'seller', price = 50, deposit = 0, cut = 0 } }, 0)
    T.eq(#spec.comps, 1); T.eq(spec.comps[1].copper, 50)
  end)

  T.it('an invoice that does not add up falls back to one mailMoney expectation', function()
    local _, _, ns = L.boot()
    local spec = ns.Sources.MailSpec({ money = 149, cod = 0, subject = 's', invoice = { kind = 'seller', price = 50, deposit = 100, cut = 2 } }, 0)
    T.eq(spec.src, 'mailMoney'); T.isnil(spec.comps)
  end)

  T.it('COD owed (cod > 0) and money-less mails create no expectation; COD paid stays OTHER (Q-1)', function()
    local W, _, ns = L.boot()
    open(W)
    L.inbox(W, { L.codMail(100) }); W:advance(1.0)
    L.inbox(W, {}); W:advance(0.106); L.pay(W, -100); W:advance(2.3)
    local e = entries(ns)[1]
    T.eq(e.src, 'other'); T.eq(e.copper, -100); T.eq(e.conf, 'low')
    T.eq(ns.Sources.Stats().sources.mailExp, 0); T.eq(ns.Sources.Stats().sources.mailSkippedCod, 1)
  end)

  T.it('taking only the items of a mail that also holds money creates nothing', function()
    local W, _, ns = L.boot()
    open(W)
    local both = { header = World.header({ icon = 1, sender = 'X', subject = 'both', money = 20, itemCount = 2, firstQty = 1 }) }
    local moneyOnly = { header = World.header({ icon = 1, sender = 'X', subject = 'both', money = 20, itemCount = 1, firstQty = 1 }) }
    L.inbox(W, { both }); W:advance(1.0)
    L.inbox(W, { moneyOnly }); W:advance(1.5)
    T.eq(ns.Sources.Stats().sources.mailVanished, 0); T.eq(ns.Sources.Stats().sources.mailExp, 0)
  end)

  T.it('two identical money mails taken one after the other give two expectations', function()
    local W, _, ns = L.boot()
    open(W)
    L.inbox(W, { L.moneyMail(30), L.moneyMail(30) }); W:advance(1.0)
    L.inbox(W, { L.moneyMail(30) }); W:advance(0.2); L.pay(W, 30); W:advance(0.7)
    L.inbox(W, {}); W:advance(0.2); L.pay(W, 30); W:advance(0.3)
    T.eq(#entries(ns), 2)
    T.eq(entries(ns)[1].src, 'mailMoney'); T.eq(entries(ns)[2].src, 'mailMoney')
  end)

  T.it('a money mail that vanished without money (deleted/expired) is counted unmatched, no entry', function()
    local W, _, ns = L.boot()
    open(W)
    L.inbox(W, { L.moneyMail(77) }); W:advance(1.0)
    L.inbox(W, {}); W:advance(2.0)
    T.eq(#entries(ns), 0); T.eq(ns.Sources.Stats().unmatched, 1)
  end)

  T.it('reopening the mailbox starts with a new baseline (a mail that expired in between creates nothing)', function()
    local W, _, ns = L.boot()
    open(W)
    L.inbox(W, { L.moneyMail(77) }); W:advance(1.0)
    W.state.mailShown = false; W:advance(1.0)
    open(W)
    L.inbox(W, {}); W:advance(2.0)
    T.eq(ns.Sources.Stats().sources.mailExp, 0)
    T.eq(ns.Sources.Stats().sources.mailBaselines, 2)
  end)
end)

