T.describe('Sources: statistics and invariant', function()
  T.it('Stats reports the review indicators and the invariant holds after a mixed session', function()
    local W, _, ns = L.boot()
    coinLoot(W, nil, { 8 }); W:advance(0.4); L.pay(W, 8)
    W:fire('QUEST_TURNED_IN', 1, 2, 30); W:advance(0.04); L.pay(W, 30)
    L.pay(W, -17); W:advance(2.0)                           -- unexplained
    W:fire('QUEST_TURNED_IN', 2, 2, 55); W:advance(2.0)     -- never paid
    local s = ns.Sources.Stats()
    T.eq(s.total, 3); T.eq(s.sumDeltas, 21); T.eq(s.sumEntries, 21)
    T.eq(s.otherShareEntries, 1 / 3)
    T.near(s.otherShareValue, 17 / 55, 1e-9)
    T.eq(s.largestOther, 17); T.eq(s.gapCount, 0); T.eq(s.unmatched, 1); T.eq(s.pending, 0)
    T.truthy(ns.Sources.Reconciler():Check())
    T.truthy(s.sources.ticks > 0)
  end)
end)
