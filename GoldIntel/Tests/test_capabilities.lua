--[[
Tests / test_capabilities.lua                       (Phase 2: Core/Capabilities.lua, D-034)

The stage model: valid -> registered -> delivered -> payloadUsable for events, present for APIs.
Key property: nothing is assumed delivered or usable until it is observed.
]]

local T = require('testlib')
local Loader = require('loader')

local function boot(fakeOpts)
  local W, P, ns = Loader.boot(fakeOpts or {})
  return W, P, ns, ns.Capabilities
end

T.describe('Capabilities.Set and Level', function()
  T.it('event stages follow the level ladder', function()
    local _, _, _, C = boot()
    local n = 'event.TEST_X'
    T.eq(C.Level(n), 'unknown')
    C.Set(n, 'valid', true);         T.eq(C.Level(n), 'valid')
    C.Set(n, 'registered', true);    T.eq(C.Level(n), 'registered')
    C.Set(n, 'delivered', true);     T.eq(C.Level(n), 'delivered')
    C.Set(n, 'payloadUsable', true); T.eq(C.Level(n), 'payloadUsable')
    T.truthy(C.Usable(n))
  end)

  T.it('payloadUsable alone is not enough: delivery must be observed', function()
    local _, _, _, C = boot()
    C.Set('event.TEST_X', 'registered', true)
    C.Set('event.TEST_X', 'payloadUsable', true)
    T.eq(C.Level('event.TEST_X'), 'registered')
    T.falsy(C.Usable('event.TEST_X'))
  end)

  T.it('failures dominate: invalid, blocked and unusable payloads', function()
    local _, _, _, C = boot()
    C.Set('event.A', 'valid', false); C.Set('event.A', 'registered', true)
    T.eq(C.Level('event.A'), 'invalid')
    C.Set('event.B', 'valid', true); C.Set('event.B', 'registered', false)
    T.eq(C.Level('event.B'), 'blocked')
    C.Set('event.C', 'registered', true); C.Set('event.C', 'delivered', true); C.Set('event.C', 'payloadUsable', false)
    T.eq(C.Level('event.C'), 'payloadUnusable')
    T.falsy(C.Usable('event.C'))
  end)

  T.it('delivered can never be set to false: not observed is not not delivered', function()
    local _, _, _, C = boot()
    local ok, err = C.Set('event.A', 'delivered', false)
    T.isnil(ok)
    T.truthy(err:find('never false', 1, true))
    T.isnil(C.Stage('event.A', 'delivered'))
  end)

  T.it('api capabilities have a single present stage', function()
    local _, _, _, C = boot()
    T.eq(C.Level('map.cmap'), 'unknown')
    C.Set('x.api', 'present', true);  T.eq(C.Level('x.api'), 'present'); T.truthy(C.Usable('x.api'))
    C.Set('x.api', 'present', false); T.eq(C.Level('x.api'), 'absent');  T.falsy(C.Usable('x.api'))
    C.Set('x.api', 'present', nil);   T.eq(C.Level('x.api'), 'unknown')
  end)

  T.it('rejects stages of the wrong kind and non-boolean values', function()
    local _, _, _, C = boot()
    T.isnil((C.Set('x.api', 'registered', true)))
    T.isnil((C.Set('event.X', 'present', true)))
    T.isnil((C.Set('event.X', 'valid', 'yes')))
    T.isnil((C.Set('', 'present', true)))
    T.isnil((C.Set(5, 'present', true)))
  end)

  T.it('Set reports whether anything changed', function()
    local _, _, _, C = boot()
    T.truthy(C.Set('event.X', 'valid', true))
    T.falsy(C.Set('event.X', 'valid', true))
    T.truthy(C.Set('event.X', 'valid', false))
  end)

  T.it('Get returns a copy with level, stages and notes', function()
    local _, _, _, C = boot()
    C.Set('event.X', 'registered', false, 'blocked by test')
    local g = C.Get('event.X')
    T.eq(g.kind, 'event'); T.eq(g.level, 'blocked'); T.eq(g.stages.registered, false); T.eq(g.notes.registered, 'blocked by test')
    g.stages.registered = true
    T.eq(C.Stage('event.X', 'registered'), false)
    T.isnil(C.Get('event.NOPE'))
  end)

  T.it('changes are announced with the resulting level', function()
    local _, _, ns, C = boot()
    local seen = {}
    ns.Bus.On('CAPABILITY_STAGE_CHANGED', function(p) seen[#seen + 1] = p.cap .. ':' .. p.stage .. '=' .. tostring(p.value) .. '->' .. p.level end)
    C.Set('event.X', 'valid', true)
    C.Set('event.X', 'registered', true)
    C.Set('event.X', 'registered', true)
    T.eq(seen, { 'event.X:valid=true->valid', 'event.X:registered=true->registered' })
  end)

  T.it('Names filters by kind and is sorted; Summary counts per level', function()
    local _, _, _, C = boot()
    C.Reset()
    C.Set('event.B', 'registered', true); C.Set('event.A', 'registered', true); C.Set('z.api', 'present', true)
    T.eq(C.Names('event'), { 'event.A', 'event.B' })
    T.eq(C.Names('api'), { 'z.api' })
    local s = C.Summary()
    T.eq(s.event.registered, 2)
    T.eq(s.api.present, 1)
  end)
end)

T.describe('Capabilities integration with the Platform', function()
  T.it('after startup the Phase 1 events are registered and NOT assumed delivered', function()
    local W, _, _, C = boot()
    W:login()
    -- login events were delivered by the fake client; zone/level/regen events were not
    T.eq(C.Stage('event.PLAYER_MONEY', 'registered'), true)
    T.isnil(C.Stage('event.PLAYER_MONEY', 'delivered'))
    T.eq(C.Level('event.PLAYER_MONEY'), 'registered')
    T.eq(C.Level('event.PLAYER_LEVEL_UP'), 'registered')
    T.falsy(C.Usable('event.PLAYER_MONEY'))
  end)

  T.it('a delivered money event with a readable balance reaches payloadUsable', function()
    local W, _, _, C = boot()
    W:login()
    W.state.money = 500
    W:fire('PLAYER_MONEY')
    T.eq(C.Stage('event.PLAYER_MONEY', 'delivered'), true)
    T.eq(C.Stage('event.PLAYER_MONEY', 'payloadUsable'), true)
    T.eq(C.Level('event.PLAYER_MONEY'), 'payloadUsable')
    T.truthy(C.Usable('event.PLAYER_MONEY'))
  end)

  T.it('a secret balance makes the money payload unusable', function()
    local W, _, _, C = boot()
    W:login()
    W.env.issecretvalue = function(v) return v == 777 end
    W.state.money = 777
    W:fire('PLAYER_MONEY')
    T.eq(C.Stage('event.PLAYER_MONEY', 'payloadUsable'), false)
    T.eq(C.Level('event.PLAYER_MONEY'), 'payloadUnusable')
    W.state.money = 900
    W:fire('PLAYER_MONEY')
    T.eq(C.Level('event.PLAYER_MONEY'), 'payloadUsable')
  end)

  T.it('a level-up with a readable level makes that payload usable', function()
    local W, _, _, C = boot()
    W:login()
    W:fire('PLAYER_LEVEL_UP', 13)
    T.eq(C.Level('event.PLAYER_LEVEL_UP'), 'payloadUsable')
  end)

  T.it('the restricted combat log event is blocked by policy and never registered', function()
    local W, P, _, C = boot()
    W.state.forbiddenEvents.COMBAT_LOG_EVENT_UNFILTERED = true
    W:login()
    P.Events.Bind('COMBAT_LOG_EVENT_UNFILTERED', function() end)
    T.eq(C.Level('event.COMBAT_LOG_EVENT_UNFILTERED'), 'blocked')
    T.truthy(C.Get('event.COMBAT_LOG_EVENT_UNFILTERED').notes.registered:find('restricted', 1, true))
    T.eq(#W.forbidden, 0)
  end)

  T.it('a silently blocked registration shows as blocked, not registered', function()
    local W, P, _, C = boot()
    W:login()
    W.state.forbiddenEvents.LOOT_OPENED = true
    P.Events.Bind('LOOT_OPENED', function() end)
    T.eq(C.Level('event.LOOT_OPENED'), 'blocked')
  end)

  T.it('an event the client does not know is invalid', function()
    local W, P, _, C = boot()
    W:login()
    W.state.invalidEvents.NO_SUCH_EVENT = true
    P.Events.Bind('NO_SUCH_EVENT', function() end)
    T.eq(C.Stage('event.NO_SUCH_EVENT', 'valid'), false)
    T.eq(C.Level('event.NO_SUCH_EVENT'), 'invalid')
  end)

  T.it('api capabilities mirror the Platform, including unknown ones from the probe', function()
    local W, _, _, C = boot()
    W:login()
    T.eq(C.Level('map.cmap'), 'present')
    T.eq(C.Level('mail.api'), 'absent')
    T.eq(C.Level('combatlog.event'), 'unknown')
    T.truthy(C.Get('combatlog.event').notes.present:find('restricted', 1, true))
  end)

  T.it('later Platform capability changes flow in', function()
    local W, P, _, C = boot()
    W:login()
    P.SetCap('test.capability', true)
    T.eq(C.Level('test.capability'), 'present')
    P.SetCap('test.capability', false)
    T.eq(C.Level('test.capability'), 'absent')
  end)

  T.it('Attach is idempotent: no duplicate subscriptions', function()
    local W, _, ns, C = boot()
    W:login()
    local n = 0
    ns.Bus.On('CAPABILITY_STAGE_CHANGED', function() n = n + 1 end)
    C.Attach(); C.Attach()
    W.state.money = 1; W:fire('PLAYER_MONEY')
    T.eq(n, 2, 'one delivered and one payloadUsable change, each once')
  end)
end)

T.describe('Capabilities snapshot and persistence', function()
  T.it('Snapshot is plain data with levels and known stages only', function()
    local W, _, _, C = boot()
    W:login()
    local snap = C.Snapshot()
    T.eq(snap['event.PLAYER_MONEY'].level, 'registered')
    T.eq(snap['event.PLAYER_MONEY'].registered, true)
    T.isnil(snap['event.PLAYER_MONEY'].delivered)
    T.eq(snap['map.cmap'].present, true)
  end)

  T.it('Persist writes the snapshot, event statistics and timestamp into the runtime section', function()
    local W, _, ns, C = boot()
    W:login()
    W.state.money = 5; W:fire('PLAYER_MONEY')
    T.truthy(C.Persist())
    local rt = ns.Store.Section('runtime')
    T.eq(rt.capabilities['event.PLAYER_MONEY'].level, 'payloadUsable')
    T.eq(rt.eventStats.PLAYER_MONEY.delivered, 1)
    T.truthy(rt.generatedAt)
    T.eq(rt.addonVersion, '0.6.0-passive')
  end)

  T.it('changes schedule one throttled snapshot, not one per change', function()
    local W, _, ns, C = boot()
    W:login()
    ns.Store.Section('runtime').generatedAt = nil
    for i = 1, 20 do C.Set('event.BURST_' .. i, 'valid', true) end
    T.isnil(ns.Store.Section('runtime').generatedAt)
    W:advance(C.PERSIST_DELAY + 1)
    T.truthy(ns.Store.Section('runtime').generatedAt)
    T.truthy(ns.Store.Section('runtime').capabilities['event.BURST_20'])
  end)

  T.it('Persist is a no-op before the store is open', function()
    local _, _, _, C = boot()
    T.falsy(C.Persist())
  end)
end)

T.describe('Capabilities: command output reaches the saved data', function()
  T.it('Persist writes the last 100 printed lines and the total count', function()
    local W, P, ns = Loader.boot()
    W:login()
    P.ClearOutput()
    for i = 1, 130 do P.Print('chat line ' .. i) end
    ns.Capabilities.Persist()
    local rt = ns.Store.Section('runtime')
    T.eq(#rt.output, 100)
    T.truthy(rt.output[100]:find('chat line 130', 1, true))
    T.truthy(rt.output[1]:find('chat line 31', 1, true))
    T.eq(rt.outputTotal, 130)
  end)

  T.it('running a command schedules a snapshot so its output is saved within seconds, without a logout', function()
    local W, _, ns = Loader.boot()
    W:login()
    W.env.SlashCmdList.GOLDINTEL('caps events')
    W:advance(ns.Capabilities.PERSIST_DELAY + 1)
    local joined = table.concat(ns.Store.Section('runtime').output, '\n')
    T.truthy(joined:find('event.PLAYER_MONEY', 1, true))
    T.truthy(joined:find('registered=yes', 1, true))
  end)

  T.it('logout saves the final output; the saved data stays plain and serializable', function()
    local sim = require('svsim')
    local W, _, ns = Loader.boot()
    W:login()
    W.env.SlashCmdList.GOLDINTEL('status')
    W:fire('PLAYER_LOGOUT')
    local db = sim.parse(sim.dump(W.env.GoldIntelDB))
    local joined = table.concat(db.runtime.output, '\n')
    T.truthy(joined:find('operational=true', 1, true))
  end)
end)
