--[[ Tests / test_chat.lua (0.3.5 evidence build): Platform/Chat.lua records CHAT_MSG_MONEY, emits nothing. ]]
local T = require('testlib')
local World = require('collectworld')

local function boot()
  local W, P, ns = World.boot()
  W.state.money = 100000; W:fire('PLAYER_MONEY')
  ns.Collector.On({})
  W:advance(1.0)
  return W, P, ns
end
local function has(list, text)
  for _, l in ipairs(list) do if l:find(text, 1, true) then return l end end
end

T.describe('Chat evidence recorder', function()
  T.it('is registered by collect on and records text with parsed copper', function()
    local W, P, ns = boot()
    T.truthy(P.Events.Stats('CHAT_MSG_MONEY').registered)
    W:fire('CHAT_MSG_MONEY', 'Your share of the loot is 1 Silver 5 Copper.')
    local r = P.ChatModule.Recent()
    T.eq(r[#r].text, 'Your share of the loot is 1 Silver 5 Copper.')
    T.eq(r[#r].copper, 105)
    T.eq(P.ChatModule.stats.text, 1)
  end)
  T.it('parses gold silver copper and rejects text without amounts', function()
    local _, P = boot()
    T.eq(P.ChatModule.ParseMoney('3 Gold 4 Silver 5 Copper'), 30405)
    T.eq(P.ChatModule.ParseMoney('7 Copper'), 7)
    T.eq(P.ChatModule.ParseMoney('nothing here'), nil)
    T.eq(P.ChatModule.ParseMoney(42), nil)
  end)
  T.it('handles secret and non-string text', function()
    local W, P = boot()
    W:fire('CHAT_MSG_MONEY', { __secret = true })
    W:fire('CHAT_MSG_MONEY', 12)
    T.eq(P.ChatModule.stats.secret, 1)
    T.eq(P.ChatModule.stats.nonString, 1)
  end)
  T.it('keeps a bounded ring', function()
    local W, P = boot()
    for i = 1, 30 do W:fire('CHAT_MSG_MONEY', i .. ' Copper') end
    T.eq(#P.ChatModule.Recent(), P.ChatModule.RING)
  end)
  T.it('a failing tap is swallowed and no ledger entry is created', function()
    local W, P, ns = boot()
    P.ChatModule.tap = function() error('boom') end
    W:fire('CHAT_MSG_MONEY', '5 Copper')
    T.eq(#ns.Sources.Entries(), 0)
    T.eq(P.ChatModule.stats.seen, 1)
  end)
end)

T.describe('trace chat and group lines', function()
  T.it('writes CHAT_MONEY and the EVIDENCE line, with group text', function()
    local W, _, ns = boot()
    W.state.group = { n = 2 }
    W:fire('CHAT_MSG_MONEY', 'Your share of the loot is 3 Copper.')
    local L = ns.Trace.Lines(400)
    T.truthy(has(L, 'EVIDENCE chatMoneyRegistered=true'))
    local c = has(L, 'CHAT_MONEY parsed=3')
    T.truthy(c and c:find('grp=2/true/false', 1, true), tostring(c))
    T.truthy(c:find('Your share of the loot', 1, true))
  end)
  T.it('MONEY lines carry the group and unavailable group APIs are reported', function()
    local W, _, ns = boot()
    W.state.group = { n = 1 }
    W.state.money = W.state.money + 4; W:fire('PLAYER_MONEY')
    T.truthy(has(ns.Trace.Lines(400), 'grp=1/false/false'))
    W.state.group = 'absent'
    W.state.money = W.state.money + 4; W:fire('PLAYER_MONEY')
    T.truthy(has(ns.Trace.Lines(400), 'grp='))
  end)
end)
